    // 점수 "보스 세기" 항의 패턴 가중치(PLAN_SCORE_1116). 패턴이 어려울수록(맞을 확률이 높을수록) 크다.
    // 범위 0.6~1.8, 아래 표에 있는 패턴들의 평균 = 1.0. 표에 없는 패턴 ID는 1.0.
    //
    // v0 (11/17) 근거: 11/15 규칙 봇 시범 데이터(텔레메트리 20261115-001143, 초보·중급·숙련 × 4판, 고정 난이도)의
    //   boss_strike 153개. 패턴별 피격률(hit / 타격 수)을 전체 피격률 p0 = 44/153 ≈ 0.288 쪽으로 줄인 뒤
    //   (p = (hit + 8·p0) / (n + 8): 타격이 적은 패턴일수록 1.0에 가깝다) p / p0을 0.6~1.8로 자르고 평균 1.0으로 맞췄다.
    //   2페이즈 강화판(201~204, 210)은 시범 데이터에 없어 같은 동작의 1페이즈 값을 그대로 쓴다.
    //   시범 데이터에 없는 212·213·303은 기본값(평균에 맞춘 0.95)이다.
    //   봇은 받아치기 자세(107)에 일부러 공격을 넣어 11/11 맞았고, 물러나며 베기(106)·도약(105)은 거의 안 맞았다.
    // v1 (11/19~20 예정): 봇 평가·사람 기록으로 로지스틱 회귀(패턴·거리·페이즈·실력 단계)를 다시 돌려 이 표만 바꾼다.
    public static class ScorePatternWeights
    {
        public const string Version = "v0";
        public const float Min = 0.6f, Max = 1.8f, Default = 1f;

        // 패턴 ID → 가중치. 주석: 시범 데이터 피격 수/타격 수.
        private static readonly Dictionary<int, float> s_weights = new Dictionary<int, float>
        {
            { 101, 1.06f }, // 내려베기 6/18
            { 102, 0.70f }, // 3연격 7/36
            { 103, 0.71f }, // 돌진 찌르기 2/12
            { 104, 1.51f }, // 가로베기 5/8
            { 105, 0.60f }, // 거대검 도약 내려찍기 0/7
            { 106, 0.60f }, // 물러나며 베기 1/24
            { 107, 1.69f }, // 받아치기 자세 11/11
            { 108, 1.21f }, // 검흔 파동 1/1
            { 109, 0.87f }, // 모아 올려치기 4/16
            { 110, 1.21f }, // 원거리 낙검 5/12
            { 201, 1.06f }, // 내려베기+ (101 값)
            { 202, 0.70f }, // 3연격+ (102 값)
            { 203, 0.71f }, // 돌진 찌르기+ (103 값)
            { 204, 1.51f }, // 가로베기+ (104 값)
            { 210, 1.21f }, // 원거리 낙검+ (110 값)
            { 211, 0.85f }, // 환영 내려베기 0/1
            { 212, 0.95f }, // 영체 검 낙하 (자료 없음)
            { 213, 0.95f }, // 거대 검 (자료 없음)
            { 300, 0.95f }, // 페이즈 전환 2/7
            { 303, 0.95f }, // 마지막 가르침 (자료 없음)
        };

        public static IReadOnlyDictionary<int, float> All => s_weights;

        public static float For(int patternId) => s_weights.TryGetValue(patternId, out float weight) ? weight : Default;
    }
}
